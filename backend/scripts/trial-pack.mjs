// Regenerates src/emails/trial-pack.ts from the trial copy pack
// (my-apps/trial-3-giorni/testi/email): the ember template and the
// PC Tweaker and Uninstaller strings in six languages. Edit the pack, then:
//   node scripts/trial-pack.mjs <path-to-testi/email>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const pack = process.argv[2];
if (!pack) throw new Error("usage: node scripts/trial-pack.mjs <path-to-testi/email>");
const read = (...parts) => readFileSync(join(pack, ...parts), "utf8");
const strings = {};
for (const [product, dir] of [["pctweaker", "pc-tweaker"], ["uninstaller", "uninstaller"]]) {
  strings[product] = {};
  for (const lang of ["en", "it", "fr", "es", "de", "pt"]) {
    const { common, ...sections } = JSON.parse(read("strings", dir, `${lang}.json`));
    const { _note, samplePlan, sampleTrialEnd, sampleAmount, sampleRenews, samplePaymentMethod, ...kept } = common;
    strings[product][lang] = { common: kept, ...sections };
  }
}
// The template's leading comment is a note for translators, not part of the mail.
const html = read("ember", "template.html").replace(/<!-- Trial emails[\s\S]*?-->\r?\n/, "");
const body = `// Generated by scripts/trial-pack.mjs from the trial copy pack. Do not edit by hand.
export const EMBER_HTML = ${JSON.stringify(html)};
export const EMBER_TEXT = ${JSON.stringify(read("ember", "template.txt"))};
export const TRIAL_STRINGS: Record<string, Record<string, Record<string, Record<string, string | Record<string, string>>>>> = ${JSON.stringify(strings, null, 1)};
`;
writeFileSync(new URL("../src/emails/trial-pack.ts", import.meta.url), body);
console.log("src/emails/trial-pack.ts written");
