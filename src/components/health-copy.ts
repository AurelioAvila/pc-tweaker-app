export type EvidenceParts = { key?: string | null; number?: number | null; name?: string | null };

/** A factor's name in the user's language; ids a newer scorer adds fall back
 *  to the English label it sends. */
export function factorLabel(lang: Lang, id: string, fallback: string): string {
  return HEALTH_COPY[lang].factors[id] ?? fallback;
}

/** The evidence sentence in the user's language, numbers in its notation
 *  (days with one decimal, everything else whole). Evidence stored before it
 *  carried a key, or a key this build does not know, shows the English. */
export function factorEvidence(
  lang: Lang,
  parts: EvidenceParts | undefined,
  fallback: string,
): string {
  const template = parts?.key ? HEALTH_COPY[lang].evidence[parts.key] : undefined;
  if (!template) return fallback;
  const days = /uptime|restart/.test(parts?.key ?? "");
  const number =
    parts?.number == null
      ? ""
      : new Intl.NumberFormat(localeOf(lang), {
          minimumFractionDigits: days ? 1 : 0,
          maximumFractionDigits: days ? 1 : 0,
        }).format(parts.number);
  return template.replace("{number}", number).replace("{name}", parts?.name ?? "");
}
